"""Write Pandoc-ready markdown tables from the A02 habitat area statistics (A03).

Reads data/out/stats/A02_Habitat-area-stats.csv and writes the same tables in two layouts:
  data/out/stats/A03_Habitat-area-tables_combined.md  benthic and geomorphic side by side
  data/out/stats/A03_Habitat-area-tables_separate.md  a benthic table followed by a geomorphic table

See A02-habitat-area-stats-spec.md for the table definitions.
"""
import sys
from pathlib import Path

import pandas as pd

STATS = Path("data/out/stats")
IN_CSV = STATS / "A02_Habitat-area-stats.csv"
OUT_COMBINED = STATS / "A03_Habitat-area-tables_combined.md"
OUT_SEPARATE = STATS / "A03_Habitat-area-tables_separate.md"

MAPPINGS = ["Benthic", "Geomorphic"]
DATASET = "Dataset"
ANALYSIS = "Analysis-regions v1"
IMCRA = "IMCRA v4.0 Meso-scale Bioregions (2023)"
CAPAD = "CAPAD 2024 - Marine"
OUTSIDE = "Outside all regions"
OUTSIDE_LABELS = {ANALYSIS: "Outside all Analysis-regions", IMCRA: "Outside IMCRA meso-scale bioregions"}
AREA = "Area (km²)"


def fmt(value):
    if value > 0 and round(value, 1) == 0:
        return "<0.1"
    return f"{value:,.1f}"


def bold(text):
    return f"**{text}**" if text else ""


def md_table(header, align, rows):
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join(":---" if a == "l" else "---:" for a in align) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def regions(df, regionalisation):
    """List of (label, {mapping: [(class, area), ...]}) in CSV order, non-zero classes only."""
    sub = df[df["Regionalisation"] == regionalisation]
    result = []
    for (rtype, name), group in sub.groupby(["Region_type", "Region_name"], sort=False):
        if regionalisation == DATASET:
            label = "All mapped areas"
        elif regionalisation == CAPAD:
            label = f"{name} - {rtype}"
        elif name == OUTSIDE:
            label = OUTSIDE_LABELS[regionalisation]
        else:
            label = name
        classes = {m: [(r.Class_name, r.Area_km2) for r in group[group["Mapping"] == m].itertuples()
                       if r.Area_km2 > 0] for m in MAPPINGS}
        result.append((label, classes))
    return result


def combined(region_list):
    rows = []
    for label, classes in region_list:
        b, g = classes["Benthic"], classes["Geomorphic"]
        if not b and not g:
            continue
        for i in range(max(len(b), len(g))):
            rows.append([label if i == 0 else "",
                         b[i][0] if i < len(b) else "", fmt(b[i][1]) if i < len(b) else "",
                         g[i][0] if i < len(g) else "", fmt(g[i][1]) if i < len(g) else ""])
        rows.append(["**Total**", "", bold(fmt(sum(a for _, a in b))) if b else "",
                     "", bold(fmt(sum(a for _, a in g))) if g else ""])
    return md_table(["Region", "Benthic class", AREA, "Geomorphic class", AREA], "llrlr", rows)


def separate(region_list, mapping):
    rows = []
    for label, classes in region_list:
        listed = classes[mapping]
        if not listed:
            continue
        for i, (name, area) in enumerate(listed):
            rows.append([label if i == 0 else "", name, fmt(area)])
        rows.append(["**Total**", "", bold(fmt(sum(a for _, a in listed)))])
    return md_table(["Region", "Class", AREA], "llr", rows)


def subregion_totals(df):
    def mapped(regionalisation, name, mapping):
        sel = df[(df["Regionalisation"] == regionalisation) & (df["Region_name"] == name)
                 & (df["Mapping"] == mapping)]
        return sel["Area_km2"].sum()

    rows = []
    names = df[df["Regionalisation"] == ANALYSIS]["Region_name"].drop_duplicates()
    for name in names:
        label = OUTSIDE_LABELS[ANALYSIS] if name == OUTSIDE else name
        rows.append([label] + [fmt(mapped(ANALYSIS, name, m)) for m in MAPPINGS])
    rows.append(["**Total**"] + [bold(fmt(mapped(DATASET, "All", m))) for m in MAPPINGS])
    return md_table(["Subregion", "Benthic area (km²)", "Geomorphic area (km²)"], "lrr", rows)


TABLES = [
    # (section, caption, regionalisation)
    ("Results", "Area of each benthic and geomorphic class across the whole mapping.", DATASET),
    ("Results", "Total mapped benthic and geomorphic area by NESP 3.17 Analysis-region subregion.", None),
    ("Appendix", "Area of each benthic and geomorphic class by NESP 3.17 Analysis-region subregion.", ANALYSIS),
    ("Appendix", "Area of each benthic and geomorphic class by IMCRA v4.0 meso-scale bioregion.", IMCRA),
    ("Appendix", "Area of each benthic and geomorphic class by CAPAD 2024 marine protected area. "
                 "Protected areas can overlap, so their areas are not summed.", CAPAD),
]


def write(path, layout, df):
    parts = [f"<!-- Generated by A03-habitat-area-tables.py from {IN_CSV.as_posix()} "
             f"({layout} layout). Do not edit by hand. -->"]
    number, section = 1, None
    for table_section, caption, regionalisation in TABLES:
        if table_section != section:
            section = table_section
            parts.append(f"## {section} tables")
        if regionalisation is None:
            parts += [f"**Table {number}.** {caption}", subregion_totals(df)]
            number += 1
        elif layout == "combined":
            parts += [f"**Table {number}.** {caption}", combined(regions(df, regionalisation))]
            number += 1
        else:
            for mapping in MAPPINGS:
                text = caption.replace("benthic and geomorphic class", f"{mapping.lower()} class")
                parts += [f"**Table {number}.** {text}", separate(regions(df, regionalisation), mapping)]
                number += 1
    path.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    print(f"Wrote {path}")


def main():
    if not IN_CSV.exists():
        sys.exit(f"{IN_CSV} not found. Run A02-habitat-area-stats.py first.")
    df = pd.read_csv(IN_CSV, keep_default_na=False)
    df = df[df["Class_name"] != "Unknown"]
    write(OUT_COMBINED, "combined", df)
    write(OUT_SEPARATE, "separate", df)


if __name__ == "__main__":
    main()
